"""Generate src/beli/_async_resources.py from src/beli/_resources.py.

Run after editing the sync resources:

    python scripts/gen_async.py

``--check`` exits non-zero if the generated file is stale (used in CI and tests).
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "beli" / "_resources.py"
DST = ROOT / "src" / "beli" / "_async_resources.py"

HEADER = '"""Async resource groups. GENERATED by scripts/gen_async.py from _resources.py; do not edit."""\n'


def transform(source: str) -> str:
    body = source.split('"""', 2)[2].lstrip("\n")
    rules = [
        (r"\bSyncTransport\b", "AsyncTransport"),
        (r"\bSyncResource\b", "AsyncResource"),
        (r"^class (\w+)\(AsyncResource\)", r"class Async\1(AsyncResource)"),
        (r"^class AsyncAsyncResource:", "class AsyncResource:"),
        (r"^(\s+)def (?!__init__)", r"\1async def "),
        (r"(?<!def )\bself\._send\(", "await self._send("),
        (r"(?<!def )\bself\.(list|get)\(", r"await self.\1("),
    ]
    for pattern, repl in rules:
        body = re.sub(pattern, repl, body, flags=re.M)
    code = HEADER + "\n" + body
    # Match the repo's formatting so --check is stable.
    result = subprocess.run(
        ["ruff", "format", "--stdin-filename", str(DST), "-"],
        input=code,
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    return result.stdout if result.returncode == 0 else code


def main() -> int:
    out = transform(SRC.read_text())
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text() != out:
            print("src/beli/_async_resources.py is stale; run python scripts/gen_async.py")
            return 1
        return 0
    DST.write_text(out)
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
